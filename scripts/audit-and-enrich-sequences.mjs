  // Update locked prompt template and context for every sequence
  let hash = 0;
  const key = String(seq.id || seq.name || '');
  for (let i = 0; i < key.length; i++) {
    hash = ((hash << 5) - hash) + key.charCodeAt(i);
    hash |= 0;
  }
  const profile = seq.modelProfile || (Math.abs(hash) % 2 === 0 ? 'male' : 'female');
  const refUrl =
    profile === 'male'
      ? '/images/athletes/athletico-male-reference.jpg'
      : '/images/athletes/athletico-female-reference.jpg';
  const refSha =
    profile === 'male'
      ? '132c39d363c91a4d49e117c408471bfcfa99d018e003b26ccec6519261569bd5'
      : '59c9c2fc50bf64bc9e7e462084b068d2bf2272741b84e0138426b63b4df081c6';

  if (!seq.visualization) seq.visualization = {};
  seq.visualization.version = 1;
  seq.visualization.referenceProfile = profile;
  seq.visualization.referenceImage = refUrl;
  seq.visualization.referenceSha256 = refSha;
  seq.visualization.promptTemplate = lockedPromptFor(refUrl, refSha);
  seq.visualization.fixedVisualContext = FIXED_CONTEXT;
