def exercises(scope='first-100'):
    rows = json.loads(subprocess.check_output(['node', str(ROOT / 'scripts/image-catalog.mjs')], cwd=ROOT))
    if scope == 'all':
        if len({e['id'] for e in rows}) != len(rows):
            raise ValueError('Duplicate exercise IDs')
        originals = {f'functional-{i:03}' for i in range(1, 101)}
        return sorted(rows, key=lambda e: (e['id'] not in originals, e['id']))
    selected = [e for e in rows if e['id'] in {f'functional-{i:03}' for i in range(1, 101)}]
    selected.sort(key=lambda e: e['id'])
    if len(selected) != 100 or len({e['id'] for e in selected}) != 100:
        raise ValueError('Expected exactly the explicit functional-001..100 catalog')
    return selected


def job_for(e):
    profile = profile_for(e)
    reference = validate_reference(PUBLIC, profile)
    frames=e.get('visualization',{}).get('frames') or e.get('productionFrames') or []
    cues = [f.get('poseDescription') or f.get('sourceCue') or f.get('label') or f.get('labelEl') for f in frames]
    approved_plan = bool(frames) and all(cues)
    count = len(frames)
    if not 4 <= count <= 10:
        raise ValueError('Storyboard must describe 4..10 ordered movement frames')
    clothes = ('black sports bra, black mid-thigh cycling shorts, white trainers, tied dark hair'
               if profile == 'female' else 'black fitted t-shirt, grey mid-thigh shorts, white trainers')
    camera = CAMERAS.get(e['id'], 'oblique side view chosen to expose the exercise joint mechanics')
    prompt = (locked_prompt(profile) + ' ' + f"One photorealistic horizontal {count}-frame storyboard for {e['name']} ({e['id']}). "
              f"EXACTLY {count} equal-width vertical columns in ONE ROW, with thin full-height white dividers at every cell boundary. No gutters or captions. "
              "Every full body, hands, feet and equipment completely inside its own column. "
              "Use the attached adult athlete photograph as the actual face/body identity reference. "
              f"Preserve hairstyle, proportions and {clothes} in every frame. "
              "Preserve the reference's modern ATHLETICO gym, dark marble, wood and warm lights; "
              "NOT a white background. Same camera, scale and lighting in all cells. "
              f"Camera: {camera}. Never a frontal view. Keep this angle fixed for the entire repetition. "
              f"Equipment: {e.get('equipment')}. Source mechanics: {e.get('instructions')}. "
              "Follow these complete per-frame specifications from left to right; the final panel marked for reuse must match frame 1 exactly: " +
              ' '.join(f"FRAME {i+1} — {f.get('label')}: {f.get('prompt') or cue}" for i,(f,cue) in enumerate(zip(frames,cues))) +
              '. Anatomically plausible exercise illustration, pending coach review.')
    return {'exerciseId': e['id'], 'name': e['name'], 'profile': profile,
            'reference': '/' + reference.relative_to(PUBLIC).as_posix(),
            'referenceSha256': digest(reference.read_bytes()), 'labels': cues,
            'frames': frames,
            'frameCount': count, 'cameraAngle': camera, 'storyboardPlanReady': approved_plan, 'prompt': prompt,
            'status': 'ready' if approved_plan else 'needs_storyboard_review'}


def split_storyboard(data, count=6):
    if type(count) is not int or not 4 <= count <= 10:
        raise ValueError('Expected 4..10 movement frames')
    info = inspect(data)
    with Image.open(io.BytesIO(data)) as im:
        if (im.width + count - 1) // count < 256 or im.height < 256:
            raise ValueError('Canvas must contain columns of at least 256 pixels')
        im = im.convert('RGB')
        # A model can return a 2171px canvas for four cells. Append <=count-1
        # pixels without resizing/cropping any source content; still require the
        # resulting exact boundaries to lie in the visible panel dividers.
        padding = (-im.width) % count
        if padding:
            padded = Image.new('RGB', (im.width + padding, im.height), (255, 255, 255))
            padded.paste(im, (0, 0))
            im = padded
        info['splitWidth'] = im.width
        info['rightPaddingPixels'] = padding
        width = im.width // count
        # Arithmetic alone is insufficient: models sometimes return five panels.
        # Require the exact number of full-height light dividers at the crop lines.
        pixels = im.load()
        columns = [x for x in range(1, info['width']-1)
                   if sum(min(pixels[x, y]) > 210 for y in range(im.height)) > .9 * im.height]
        groups = []
        for x in columns:
            if not groups or x > groups[-1][-1] + 1:
                groups.append([x])
            else:
                groups[-1].append(x)
        if len(groups) != count - 1 or any(not(g[0]-3 <= width*n <= g[-1]+3) for n, g in enumerate(groups, 1)):
            raise ValueError('Not the requested equal visible panels: reject rather than cutting through bodies')
        frames, boxes = [], []
        for i in range(count):
            box = (i * width, 0, (i + 1) * width, im.height)
            crop = im.crop(box)
            out = io.BytesIO()
            crop.save(out, 'WEBP', quality=90, method=6)
            frame = out.getvalue()
            inspect(frame)
            frames.append(frame)
            boxes.append(list(box))
    if len({digest(b) for b in frames}) != count:
        raise ValueError('Duplicate cropped panels')
    return frames, boxes, info


def openai_generate(job):
    if 1536 % job['frameCount'] or 1536 // job['frameCount'] < 256:
        raise ValueError('This API canvas cannot divide into the requested columns at >=256px each; supply a suitable-resolution storyboard, no generation attempted')
    key = os.environ.get('OPENAI_API_KEY')
    if not key:
        raise ValueError('OPENAI_API_KEY is absent; no API generation attempted')
    # Fixed official API, normal inherited HTTPS proxy and TLS verification.
    boundary = 'sofia-' + uuid.uuid4().hex
    parts = []
    def field(name, value):
        parts.append(f'--{boundary}\r\nContent-Disposition: form-data; name="{name}"\r\n\r\n{value}\r\n'.encode())
    field('model', 'gpt-image-1')
    field('prompt', job['prompt'])
    field('size', '1536x1024')
    field('n', '1')
    profile = job.get('profile')
    approved = validate_reference(PUBLIC, profile)
    if (job.get('reference') != '/' + approved.relative_to(PUBLIC).as_posix()
            or job.get('referenceSha256') != digest(approved.read_bytes())
            or job.get('referenceSha256') not in job.get('prompt', '')):
        raise ValueError('Approved reference path/hash missing or altered; generation blocked')
    reference = approved
    parts.append(f'--{boundary}\r\nContent-Disposition: form-data; name="image[]"; filename="reference.jpg"\r\nContent-Type: image/jpeg\r\n\r\n'.encode() + reference.read_bytes() + b'\r\n')
    parts.append(f'--{boundary}--\r\n'.encode())
    request = urllib.request.Request('https://api.openai.com/v1/images/edits', b''.join(parts),
        {'Authorization': 'Bearer ' + key, 'Content-Type': 'multipart/form-data; boundary=' + boundary})
    with urllib.request.urlopen(request, timeout=300) as response:
        document = json.load(response)
    encoded = document.get('data', [{}])[0].get('b64_json')
    if not encoded:
        raise ValueError('API response did not contain image bytes')
    return base64.b64decode(encoded, validate=True)


def register(job, data, batch, provider, activate, original_data):
    count = job.get('frameCount', len(job['labels']))
    frames, boxes, info = split_storyboard(data, count)
    manifest = read(MANIFEST)
    if MANIFEST.read_bytes() != original_data:
        raise ValueError('Image manifest changed; re-run after reconciliation')
    entry = manifest['exercises'].setdefault(job['exerciseId'], {
        'status': 'pending_visual_review', 'phases': [None] * count,
        'candidates': [], 'blockedPhases': {}})
    if activate and (entry.get('status') == 'approved' or any(
            x.get('status') == 'approved' for x in entry.get('phaseReviews', {}).values())):
        raise ValueError('Will not replace any approved sequence, even in preview')
    if entry.get('storyboardPreview') and activate:
        raise ValueError('A storyboard preview already exists; explicit separate replacement required')
    all_hashes = {digest(p.read_bytes()) for p in (PUBLIC / 'images/exercises').rglob('*.webp')}
    urls, writes = [], []
    for n, frame in enumerate(frames, 1):
        sha = digest(frame)
        if sha in all_hashes:
            raise ValueError('An identical frame already exists')
        all_hashes.add(sha)
        url = f'/images/exercises/{job["exerciseId"]}/{n:02}-{sha[:16]}.webp'
        target = PUBLIC / url.lstrip('/')
        if target.exists():
            raise ValueError('Asset collision')
        urls.append(url)
        writes.append((target, frame))
        entry.setdefault('importedCandidates', []).append({
            'phase': n, 'url': url, 'sourceExerciseId': job['exerciseId'],
            'sourcePhase': n, 'provider': provider, 'sourceSha256': info['sha256'],
            'sha256': sha, 'mappingReviewer': 'Codex explicit storyboard ID/column mapping',
            'reviewStatus': 'pending_visual_review', 'batch': batch,
            'cropBox': boxes[n-1], 'athleteReferenceSha256': job['referenceSha256']})
    # Retain legacy phase URLs and their reviews, extending only for exact new phase IDs.
    entry['phases'] += [None] * max(0, count - len(entry['phases']))
    preview = {'version': 1, 'status': 'pending_visual_review', 'batch': batch,
               'phases': urls, 'labels': job['labels'], 'provider': provider,
               'sourceSha256': info['sha256'], 'cropBoxes': boxes,
               'rightPaddingPixels': info['rightPaddingPixels'],
               'athleteReference': job['reference'], 'athleteReferenceSha256': job['referenceSha256'],
               'cameraAngle': job.get('cameraAngle', 'unspecified'),
               'coachApproved': False, 'geometryChecked': True,
               'visualReview': 'pending', 'notes': 'Equal crops verified; anatomy, identity, pose and panel boundaries require human review.'}
    if activate:
        entry['storyboardPreview'] = preview
    extension = {'PNG': 'png', 'JPEG': 'jpg', 'WEBP': 'webp'}[info['format']]
    source = PUBLIC / 'images/storyboards' / f'{job["exerciseId"]}-{info["sha256"][:16]}.{extension}'
    if source.exists():
        raise ValueError('Source storyboard already exists')
    writes.append((source, data))
    created = []
    try:
        for target, value in writes:
            target.parent.mkdir(parents=True, exist_ok=True)
            with target.open('xb') as f:
                f.write(value)
            created.append(target)
        write(MANIFEST, manifest)
    except Exception:
        for target in created:
            target.unlink(missing_ok=True)
        raise
    return {'status': 'imported', 'exerciseId': job['exerciseId'], 'sourceSha256': info['sha256'],
            'sourceUrl': '/' + source.relative_to(PUBLIC).as_posix(), 'phases': urls,
            'cropBoxes': boxes, 'rightPaddingPixels': info['rightPaddingPixels'],
            'frameCount': count, 'frameDimensions': [info['splitWidth'] // count, info['height']],
            'coachApproved': False, 'previewActivated': activate}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--batch', default='batch-20261025-001')
    p.add_argument('--scope', choices=['first-100', 'all'], default='first-100')
    p.add_argument('--start', type=int, default=1)
    p.add_argument('--limit', type=int, default=5)
    p.add_argument('--provider', choices=['plan', 'openai', 'supplied'], default='plan')
    p.add_argument('--source-dir', type=pathlib.Path)
    p.add_argument('--activate-preview', action='store_true')
    a = p.parse_args()
    selected = exercises(a.scope)
    if not 1 <= a.start <= len(selected) or not 1 <= a.limit <= 100 or a.start + a.limit - 1 > len(selected):
        p.error('Batch range must be inside the selected catalog, maximum 100 at a time')
    if not a.batch.replace('-', '').replace('_', '').isalnum():
        p.error('Unsafe batch name')
    jobs = [job_for(e) for e in selected]
    if a.provider != 'plan' and any(any(frame.get('sameImageAs') for frame in job.get('frames', [])) for job in jobs):
        p.error('Canonical Sofia sequences require one image per frame and exact reuse of sameImageAs frames. Use the per-frame production queue; composite storyboard generation is not allowed for these exercises.')
    folder = ROOT / 'docs/image-production' / a.batch
    folder.mkdir(parents=True, exist_ok=True)
    checkpoint = folder / 'checkpoint.json'
    state = read(checkpoint) if checkpoint.exists() else {'version': 1, 'batch': a.batch, 'jobs': {}}
    for job in jobs:
        saved = state['jobs'].get(job['exerciseId'])
        if saved:
            job['status'] = 'imported_pending_human_review' if saved['status'] == 'imported' else saved['status']
    write(folder / 'plan.json', {'version': 1, 'exerciseCount': len(jobs), 'scope': a.scope, 'jobs': jobs})
    if a.provider == 'plan':
        print(json.dumps({'plannedExercises': len(jobs), 'readyStoryboards': sum(j['storyboardPlanReady'] for j in jobs)}))
        return
    if a.provider == 'openai' and not os.environ.get('OPENAI_API_KEY'):
        p.error('No OPENAI_API_KEY: generation unavailable; no billable call attempted')
    lock = ROOT / '.image-import.lock'
    fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    try:
        for job in jobs[a.start-1:a.start-1+a.limit]:
            id = job['exerciseId']
            previous = state['jobs'].get(id)
            if previous:
                if previous['status'] == 'imported':
                    # A durable manifest is the source of truth on resumed runs.
                    manifest = read(MANIFEST)
                    candidates = {c['url'] for c in manifest['exercises'].get(id, {}).get('importedCandidates', [])}
                    if not all(url in candidates and (PUBLIC / url.lstrip('/')).is_file() for url in previous['phases']):
                        raise ValueError('Checkpoint/manifest mismatch; manual reconciliation required')
                    print(id, 'already imported; skipped')
                    continue
                raise ValueError(f'{id}: previous attempt requires reconciliation; no blind retry')
            if not job['storyboardPlanReady'] or len(job['labels']) != job['frameCount']:
                raise ValueError(f'{id}: exact movement plan needs review before generation')
            manifest = read(MANIFEST)
            prior = manifest['exercises'].get(id, {})
            if a.activate_preview and (prior.get('storyboardPreview') or prior.get('status') == 'approved' or
                    any(v.get('status') == 'approved' for v in prior.get('phaseReviews', {}).values())):
                raise ValueError('Preview already present or approved imagery protected; no generation attempted')
            original = MANIFEST.read_bytes()
            state['jobs'][id] = {'status': 'submission_pending', 'provider': a.provider,
                                 'requestId': uuid.uuid4().hex, 'prompt': job['prompt']}
            write(checkpoint, state)
            try:
                if a.provider == 'supplied':
                    if not a.source_dir:
                        raise ValueError('--source-dir required')
                    data = (a.source_dir / f'{id}.png').read_bytes()
                    metadata = read(a.source_dir / f'{id}.json')
                    if (metadata.get('exerciseId') != id or metadata.get('sha256') != digest(data)
                            or metadata.get('referenceSha256') != job['referenceSha256']
                            or metadata.get('reference') != job['reference']
                            or metadata.get('referenceAttached') is not True
                            or 'MANDATORY SOFIA VISUAL REFERENCE LOCK' not in metadata.get('prompt', '')
                            or job['referenceSha256'] not in metadata.get('prompt', '')
                            or metadata.get('frameCount') != job['frameCount']
                            or metadata.get('visualDecision') != 'candidate'
                            or not metadata.get('provider') or not metadata.get('prompt')):
                        raise ValueError('Supplied storyboard provenance or preliminary visual review is missing/mismatched')
                    provider = metadata['provider']
                else:
                    data = openai_generate(job)
                    provider = 'OpenAI images/edits gpt-image-1'
                raw = ROOT / '.image-production' / a.batch / f'{id}.png'
                raw.parent.mkdir(parents=True, exist_ok=True)
                with raw.open('xb') as f:
                    f.write(data)
                state['jobs'][id] = register(job, data, a.batch, provider, a.activate_preview, original)
                if a.provider == 'supplied':
                    state['jobs'][id]['generationRequest'] = metadata
                write(checkpoint, state)
                print(id, 'imported', job['frameCount'], 'pending-review frames')
            except Exception as error:
                state['jobs'][id]['status'] = 'needs_reconciliation'
                state['jobs'][id]['error'] = type(error).__name__
                write(checkpoint, state)
                raise
    finally:
        os.close(fd)
        lock.unlink()


if __name__ == '__main__':
    main()
